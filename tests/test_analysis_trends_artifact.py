"""Artifact-gated pins for the P6 field-trend layer (Track D).

Two pin kinds, disclosed per test (same convention as the P2/P3 files):

* census-class pins are generated: the test recomputes the value and
  compares it against a key of ``tests/census_snapshot.json`` (the
  snapshot key is cited in each docstring; regenerated by
  ``maicdb-census --write`` — see CODING_STANDARDS.md §6);
* module-output determinism pins (sparse row counts, grid shapes) whose
  inputs are pinned by the generated censuses alongside.

All descriptive counts (spec §5.4); no hypothesis tests (spec §6).
"""

