class TestLoaderCensuses:
    def test_full_coverage(self, records, census_snapshot):
        """Census: trends.record_count (generated pin, snapshot key —
        the 960-row artifact scale) and trends.join_vacuity (generated
        pin — same LEFT JOIN coverage censuses as the P3 file: year
        NULL 0, family NULL 0)."""
        snap = census_snapshot["trends"]
        assert len(records) == snap["record_count"]
        vacuity = {
            f: sum(1 for r in records if getattr(r, f) is None)
            for f in ("year", "family")
        }
        assert vacuity == snap["join_vacuity"]

    def test_parameter_labels_are_census_totals(self, records, census_snapshot):
        """Census: trends.parameter_census (generated pin, snapshot
        key — p50 159, conductance 265, tau_inact 93, x50 46 — the
        loader's presence detection must reproduce them exactly; this
        pins the label-vs-column pairing of PARAMETERS)."""
        census = census_snapshot["trends"]["parameter_census"]
        recomputed = {
            label: sum(1 for r in records if label in r.parameters)
            for label in census
        }
        assert recomputed == census


class TestPubsPerYear:
    def test_views_and_their_coincidence(self, records, census_snapshot):
        """Census: trends.pubs_by_family_rows / pubs_by_family_k_total /
        pub_years / pubs_total_k (generated pins, snapshot keys —
        DISTINCT (family, year, publication_id) → 188 coincides with
        DISTINCT (year, publication_id) → 188; module shapes: 107
        (year, family) cells; 33 year totals). The two views coincide
        (no publication spans two families in one year) — pinned as a
        corpus fact, not a license to sum later (the pure tests hold
        the non-additivity contract)."""
        snap = census_snapshot["trends"]
        by_family = pubs_per_year_by_family(records)
        total = pubs_per_year_total(records)
        assert len(by_family) == snap["pubs_by_family_rows"]
        assert sum(r.k for r in by_family) == snap["pubs_by_family_k_total"]
        assert len(total) == snap["pub_years"]
        assert sum(t.k for t in total) == snap["pubs_total_k"]

    def test_year_anchors(self, records, census_snapshot):
        """Census: trends.pub_year_anchors (generated pin, snapshot
        key — COUNT DISTINCT publication_id JOIN year: 2010 → 5,
        2015 → 12, 2020 → 9, 2023 → 4)."""
        total = {str(t.year): t.k for t in pubs_per_year_total(records)}
        assert {y: total[y] for y in census_snapshot["trends"]["pub_year_anchors"]} == (
            census_snapshot["trends"]["pub_year_anchors"]
        )

    def test_family_cell_anchor(self, records, census_snapshot):
        """Census: trends.pub_2010_family_split (generated pin, snapshot
        key — the 2010 family cells MSCL_MSCS 2, PIEZO 1, TRP 2;
        module output, SQL-re-derivable cell by cell)."""
        rows = {(r.family, r.k) for r in pubs_per_year_by_family(records)
                if r.year == 2010}
        assert sorted(rows) == [
            tuple(pair) for pair in census_snapshot["trends"]["pub_2010_family_split"]
        ]


class TestParameterAdoption:
    def test_grid_shape(self, records, census_snapshot):
        """Grid: trends.parameter_adoption_rows /
        parameter_adoption_year_span / parameter_label_count (generated
        pins, snapshot keys — 33 distinct years × 17 PARAMETERS entries
        = 561 rows; the corpus's years are NOT contiguous, so the year
        set is pinned by the [min, max, count] span, not a range).
        Labels (not column names) — the label set must equal the
        PARAMETERS label column (regression: a wrong unpack once
        emitted column names here)."""
        snap = census_snapshot["trends"]
        pa = parameter_adoption(records)
        assert len(pa) == snap["parameter_adoption_rows"]
        assert {r.parameter for r in pa} == {label for _, label in PARAMETERS}
        years = {r.year for r in pa}
        assert [min(years), max(years), len(years)] == snap[
            "parameter_adoption_year_span"
        ]
        assert len(PARAMETERS) == snap["parameter_label_count"]

    def test_year_totals_via_of_year(self, records, census_snapshot):
        """``of_year`` cross-foot: experiments per year.
        trends.of_year_2010 (generated pin, snapshot key — 2010 → 40)."""
        pa = parameter_adoption(records)
        of_2010 = {r.of_year for r in pa if r.year == 2010}
        assert of_2010 == {census_snapshot["trends"]["of_year_2010"]}

    def test_anchor_cells(self, records, census_snapshot):
        """Census: trends.adoption_cell_anchors / adoption_corpus_totals
        (generated pins, snapshot keys — COUNT(col) JOIN year anchors
        with column thermal_threshold_c; corpus totals re-land through
        the grid)."""
        snap = census_snapshot["trends"]
        pa = parameter_adoption(records)

        def cell(label, year):
            return next(r.k for r in pa if r.parameter == label and r.year == year)

        for key, expected in snap["adoption_cell_anchors"].items():
            label, year = key.rsplit("@", 1)
            assert cell(label, int(year)) == expected
        totals = {
            label: sum(r.k for r in pa if r.parameter == label)
            for label in snap["adoption_corpus_totals"]
        }
        assert totals == snap["adoption_corpus_totals"]


class TestAssayDrift:
    def test_grid_shape_and_none_bucket(self, records, census_snapshot):
        """Census: trends.assay_drift_rows / assay_mode_count /
        assay_none_bucket_k (generated pins, snapshot keys — 9 named
        modes + the None bucket, 39 records with no recording_mode,
        grid 33 years × 10 = 330 rows). None-in stays a structural
        check."""
        snap = census_snapshot["trends"]
        ad = assay_drift(records)
        assert len(ad) == snap["assay_drift_rows"]
        assert len({r.recording_mode for r in ad}) == snap["assay_mode_count"]
        assert None in {r.recording_mode for r in ad}
        assert sum(r.k for r in ad if r.recording_mode is None) == snap[
            "assay_none_bucket_k"
        ]

    def test_year_anchor(self, records, census_snapshot):
        """Census: trends.assay_2010_split (generated pin, snapshot
        key — COUNT JOIN year=2010 GROUP BY recording_mode; rest 0)
        cross-footed against trends.of_year_2010."""
        snap = census_snapshot["trends"]
        cells = {r.recording_mode: r.k for r in assay_drift(records)
                 if r.year == 2010 and r.k > 0}
        assert cells == snap["assay_2010_split"]
        assert sum(cells.values()) == snap["of_year_2010"]


