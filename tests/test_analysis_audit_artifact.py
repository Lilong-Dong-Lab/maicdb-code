"""Artifact-gated pins for the P3 MIMIC compliance audit (Track A).

Two pin kinds, disclosed per test (same convention as the P2 file):

* census-class pins are generated: the test recomputes the value and
  compares it against a key of ``tests/census_snapshot.json`` (the
  snapshot key is cited in each docstring; regenerated by
  ``maicdb-census --write`` — see CODING_STANDARDS.md §6);
* module-output determinism pins (era/breakdown/weighted means, heatmap
  compliance ratios) cannot be re-derived by trivial SQL without
  reimplementing the scorer — their role is regression detection; their
  INPUTS (join coverage, era sizes, group k, applicable counts) are
  pinned by the generated censuses alongside.

Enforcement caveat worth its own note: the ADR-aware any-field failure
count (pinned as ``audit.failing_any_adr`` / ``audit.adr_clean_records``)
is the NULL-safe CASE-form result. The naive
``NOT (stimulus_type = 'INDENTATION' AND probe_geometry IS NULL)``
complement form is NULL-poisoned — UNKNOWN rows drop out of the clean
set and it returns 24 instead of the true 49 (live witness 2026-11-06:
both forms ran on data-v1.0 during derivation; the module follows
ADR-0005, a NULL stimulus excludes the dependent fields).
"""

from __future__ import annotations

from pathlib import Path

import pytest
from sqlalchemy import text

from maicdb.analysis.audit import (
    breakdown,
    category_weighted_mean,
    compliance_by_year,
    field_totals,
    four_field_audit,
    heatmap,
    load_families,
    load_meta,
)
from maicdb.analysis.mimic import score_all
from maicdb.query import open_readonly

DB_PATH = Path(__file__).parents[1] / "db" / "maicdb.sqlite"

requires_db = pytest.mark.skipif(
    not DB_PATH.exists(), reason=f"published DB not found at {DB_PATH}"
)

pytestmark = requires_db


@pytest.fixture(scope="module")
def engine():
    eng = open_readonly(DB_PATH)
    yield eng
    eng.dispose()


@pytest.fixture(scope="module")
def scores(engine):
    return score_all(engine)


@pytest.fixture(scope="module")
def meta(engine):
    return load_meta(engine)


@pytest.fixture(scope="module")
def records(engine):
    with engine.connect() as conn:
        rows = conn.execute(
            text("SELECT * FROM biophysics_experiment ORDER BY maicdb_id")
        ).mappings()
        return [dict(r) for r in rows]


class TestLoaderCensuses:
    def test_full_coverage(self, scores, meta, census_snapshot):
        """Census: corpus.experiment_count (generated pin, snapshot key
        — the 960-row artifact scale) and audit.meta_join_vacuity
        (generated pin — LEFT JOIN coverage complete: zero nulls in
        family / year / journal across all rows)."""
        audit = census_snapshot["audit"]
        assert len(scores) == census_snapshot["corpus"]["experiment_count"]
        assert len(meta) == census_snapshot["corpus"]["experiment_count"]
        vacuity = {
            f: sum(1 for m in meta.values() if getattr(m, f) is None)
            for f in ("family", "year", "journal")
        }
        assert vacuity == audit["meta_join_vacuity"]

    def test_family_slices(self, engine, scores, census_snapshot):
        """Census: audit.channel_count / audit.family_slice_counts
        (generated pins, snapshot keys — channels and experiments per
        family, GROUP BY c.family over the experiment join)."""
        families = load_families(engine)
        assert len(families) == census_snapshot["audit"]["channel_count"]
        counts: dict[str, int] = {}
        for s in scores:
            counts[families[s.channel_id]] = (
                counts.get(families[s.channel_id], 0) + 1
            )
        assert counts == census_snapshot["audit"]["family_slice_counts"]

    def test_era_coverage(self, scores, meta, census_snapshot):
        """Census: audit.era_split (generated pin, snapshot key —
        publication year present on all rows; pre-2010 / post-2010 /
        unassigned row counts)."""
        era = compliance_by_year(scores, {k: m.year for k, m in meta.items()})
        assert {
            "pre": era.pre_k,
            "post": era.post_k,
            "unassigned": era.unassigned_k,
        } == census_snapshot["audit"]["era_split"]


class TestFieldTotals:
    """The family-axis-collapsed totals; always-applicable fields must
    reproduce spec §3's populated census exactly."""

    def test_environment_fields(self, scores, census_snapshot):
        """Census: audit.field_total_temperature_c / field_total_ph /
        field_total_recording_mode (generated pins, snapshot keys —
        (reported, not_extracted, applicable) triples). Compliance
        ratios stay transcribed approx pins."""
        audit = census_snapshot["audit"]
        totals = field_totals(scores)
        temp = totals["temperature_c"]
        assert [temp.reported, temp.not_extracted, temp.applicable] == audit[
            "field_total_temperature_c"
        ]
        assert temp.compliance == pytest.approx(
            audit["field_total_temperature_c"][0]
            / audit["field_total_temperature_c"][2],
            abs=1e-9,
        )
        ph = totals["ph"]
        assert [ph.reported, ph.applicable] == audit["field_total_ph"]
        rec = totals["recording_mode"]
        assert [rec.reported, rec.not_extracted, rec.applicable] == audit[
            "field_total_recording_mode"
        ]

    def test_conditional_velocity_denominator(self, scores, census_snapshot):
        """Census: audit.field_total_stimulus_velocity (generated pin,
        snapshot key — stimulus IN (INDENTATION, TOUCH, SHEAR_STRESS)
        applicability; populated → 0). ADR-aware velocity compliance is
        exactly 0.0."""
        totals = field_totals(scores)
        vel = totals["stimulus_velocity"]
        assert [vel.reported, vel.applicable] == census_snapshot["audit"][
            "field_total_stimulus_velocity"
        ]
        assert vel.compliance == 0.0

    def test_cell_type(self, scores, census_snapshot):
        """Census: audit.field_total_cell_type (generated pin, snapshot
        key — NULLIF(cell_type,'') population split)."""
        cell = field_totals(scores)["cell_type"]
        assert [cell.reported, cell.not_extracted, cell.applicable] == (
            census_snapshot["audit"]["field_total_cell_type"]
        )


class TestHeatmap:
    def test_temperature_by_family_cells(self, engine, scores, census_snapshot):
        """Census: audit.heatmap_family_keys / heatmap_temperature_reported
        (generated pins, snapshot keys — temperature_c reported per
        family; the values cross-foot to field_total_temperature_c[0])."""
        audit = census_snapshot["audit"]
        hm = heatmap(scores, load_families(engine))
        assert len(set(hm)) == audit["heatmap_family_keys"]
        per_family = {f: hm[f]["temperature_c"].reported for f in hm}
        assert per_family == audit["heatmap_temperature_reported"]
        # determinism pin: PIEZO temperature compliance 4/188
        assert hm["PIEZO"]["temperature_c"].compliance == pytest.approx(
            4 / 188, abs=1e-9
        )
        assert hm["MSCL_MSCS"]["temperature_c"].compliance == 0.0


class TestEnforcement:
    """The vault §9 four-field headline under both readings."""

    def test_as_written_row_counts(self, records, census_snapshot):
        """Census: audit.as_written_missing (generated pin, snapshot
        key — applicability ignored, vault §9's own reading) and
        audit.failing_any_as_written ([960, 960] — the 100%
        motivation number)."""
        audit = four_field_audit(records)
        rows = audit.fields
        assert {
            name: rows[name].missing_as_written
            for name in (
                "stimulus_velocity",
                "probe_geometry",
                "recording_mode",
                "experimental_context",
            )
        } == census_snapshot["audit"]["as_written_missing"]
        assert list(audit.failing_any_as_written) == census_snapshot["audit"][
            "failing_any_as_written"
        ]
        assert rows["stimulus_velocity"].as_written_fail_rate == 1.0
        assert rows["experimental_context"].as_written_fail_rate == (
            pytest.approx(894 / 960, abs=1e-9)
        )

    def test_adr_aware_row_counts(self, records, census_snapshot):
        """Census: audit.adr_missing (generated pin, snapshot key —
        [applicable, missing_when_applicable] under ADR-0005;
        recording_mode is ALWAYS applicable — the 921 figure is its
        POPULATED count, not its applicable set)."""
        audit = four_field_audit(records)
        rows = audit.fields
        assert {
            name: [rows[name].applicable, rows[name].missing_when_applicable]
            for name in (
                "stimulus_velocity",
                "probe_geometry",
                "recording_mode",
                "experimental_context",
            )
        } == census_snapshot["audit"]["adr_missing"]
        assert rows["stimulus_velocity"].adr_fail_rate == 1.0
        assert rows["recording_mode"].adr_fail_rate == pytest.approx(
            39 / 960, abs=1e-9
        )

    def test_adr_aware_any_field_null_safe(self, records, census_snapshot):
        """Census: audit.failing_any_adr / audit.adr_clean_records
        (generated pins, snapshot keys — NULL-safe CASE form, see
        module docstring for the NULL-poisoned NOT-form trap)."""
        audit = four_field_audit(records)
        assert list(audit.failing_any_adr) == census_snapshot["audit"][
            "failing_any_adr"
        ]
        # clean set cross-foot
        clean = census_snapshot["corpus"]["experiment_count"] - audit.failing_any_adr[0]
        assert clean == census_snapshot["audit"]["adr_clean_records"]

    def test_the_pair_is_the_headline(self, records, census_snapshot):
        """Spec §5.1: as-written 100% fail vs ADR-aware 911/960 — both
        numbers stated, the tri-state defense visible in the gap."""
        snap = census_snapshot["audit"]
        total = census_snapshot["corpus"]["experiment_count"]
        audit = four_field_audit(records)
        assert audit.failing_any_as_written[0] == snap["failing_any_as_written"][0]
        assert 0 < audit.failing_any_adr[0] < total
        # ...and the ADR-aware rate is still damning (~94.9%)
        assert audit.failing_any_adr[0] / total == pytest.approx(
            snap["failing_any_adr"][0] / total, abs=1e-9
        )


class TestViews:
    def test_era_contrast_determinism(self, scores, meta, census_snapshot):
        """Module-output determinism pins; inputs pinned by
        audit.era_split / audit.era_year_k (generated pins — observed
        year list and per-year k). Mean per-record compliance:
        pre-PIEZO 0.347260, post-PIEZO 0.445470 — the corpus's metadata
        reporting improved after 2010."""
        snap = census_snapshot["audit"]
        era = compliance_by_year(scores, {k: m.year for k, m in meta.items()})
        assert len(era.years) == len(snap["era_year_k"])
        assert era.years[0].year == snap["era_year_k"][0][0]
        assert era.years[-1].year == snap["era_year_k"][-1][0]
        assert era.pre_mean == pytest.approx(0.347260, abs=1e-6)
        assert era.post_mean == pytest.approx(0.445470, abs=1e-6)
        # boundary rows (determinism: first/last year)
        assert (era.years[0].k, era.years[0].mean) == (
            snap["era_year_k"][0][1], pytest.approx(0.270833, abs=1e-6),
        )
        assert (era.years[-1].k, era.years[-1].mean) == (
            snap["era_year_k"][-1][1], pytest.approx(0.346734, abs=1e-6),
        )

    def test_breakdown_crossfoot_and_groups(self, scores, meta, census_snapshot):
        """Group k cross-foots against generated censuses:
        audit.breakdown_mode_crossfoot_k / breakdown_cell_attached_k /
        breakdown_family_rows / breakdown_family_crossfoot_k /
        breakdown_mscl_k / breakdown_journal_rows /
        breakdown_journal_crossfoot_k. Determinism pins: CELL_ATTACHED
        mean 0.480381; MSCL/MscS family mean 0.432455."""
        snap = census_snapshot["audit"]
        by_mode = breakdown(scores, meta, "recording_mode")
        assert sum(g.k for g in by_mode) == snap["breakdown_mode_crossfoot_k"]
        ca = next(g for g in by_mode if g.group == "CELL_ATTACHED")
        assert ca.k == snap["breakdown_cell_attached_k"]
        assert ca.mean == pytest.approx(0.480381, abs=1e-6)
        by_family = breakdown(scores, meta, "family")
        assert len(by_family) == snap["breakdown_family_rows"]
        assert sum(g.k for g in by_family) == snap["breakdown_family_crossfoot_k"]
        mscl = next(g for g in by_family if g.group == "MSCL_MSCS")
        assert (
            mscl.k,
            mscl.mean,
        ) == (
            snap["breakdown_mscl_k"],
            pytest.approx(0.432455, abs=1e-6),
        )
        by_journal = breakdown(scores, meta, "journal")
        assert len(by_journal) == snap["breakdown_journal_rows"]
        assert sum(g.k for g in by_journal) == snap["breakdown_journal_crossfoot_k"]

    def test_weighted_sensitivity(self, scores):
        """Module-output determinism pin: environment-weighted (×2,
        others 1) mean = 0.441430, ABOVE the unweighted corpus mean
        0.421020 (P2 artifact pin) — environmental fields are reported
        comparatively well, so weighting them up lifts the score. The
        direction is the sensitivity result; the magnitudes are the
        pins."""
        weights = {"environment": 2.0, "stimulus": 1.0, "recording": 1.0,
                   "cell_context": 1.0, "analysis": 1.0}
        wmean = category_weighted_mean(scores, weights)
        assert wmean == pytest.approx(0.441430, abs=1e-6)
        unweighted = sum(s.score for s in scores) / len(scores)
        assert unweighted == pytest.approx(0.421020, abs=1e-6)
        assert wmean > unweighted
