"""Corpus baseline statistics (meta-research pass 1, 2026-11-06).

The report in ``docs/research/2026-11-06-corpus-baseline.md`` is generated by
``scripts/corpus-stats.py``. The document's §4 embeds the script's output
minus its H1, with headings demoted one level;
``test_embedded_report_matches_generated_output`` compares the whole §4
section against a fresh run byte for byte — a change in the artifact, in the
derivation, or a hand-written line added to the section fails the suite
instead of leaving a silently stale document. The narrative findings above §4 are not
generated; only the figures their tests name here are pinned.

Real-data provenance (data-v1.1 artifact, read-only). Census SQL, re-runnable
against ``db/maicdb.sqlite``:

    SELECT COUNT(*) FROM channel;                  --  12
    SELECT COUNT(*) FROM publication;              -- 216
    SELECT COUNT(*) FROM biophysics_experiment;    -- 960
    SELECT COUNT(*) FROM bioactivity;              -- 137
    SELECT COUNT(*) FROM unmapped_measurement;     --  28
    SELECT COUNT(*) FROM variant;                  -- 133
    SELECT COUNT(*) FROM compound;                 --  86
    SELECT COUNT(*) FROM external_reference;       --   6
    SELECT confidence, COUNT(*) FROM biophysics_experiment GROUP BY 1;
                                                   -- high 549, medium 400, low 11
    SELECT COUNT(DISTINCT condition_key) FROM biophysics_experiment;  -- 951
    SELECT p50_unit, COUNT(*) FROM biophysics_experiment
      WHERE p50_unit IS NOT NULL GROUP BY 1;       -- mmHg 155, psi 4
    SELECT t50_unit, COUNT(*) FROM biophysics_experiment
      WHERE t50_unit IS NOT NULL GROUP BY 1;       -- mN/m 26, dyn/cm 15
    SELECT COUNT(temperature_c) FROM biophysics_experiment;   --  85 (8.9%)
    SELECT MIN(year), MAX(year) FROM publication;  -- 1986, 2026

Journal counts are post-normalisation by the script's alias table (J Biol
Chem ≡ Journal of Biological Chemistry, PNAS ≡ its expanded form, …). The
JBC total is 24 = 13 (`Journal of Biological Chemistry`) + 11 (`J Biol
Chem`); the canonical JGP string is `The Journal of General Physiology`
(21 = 19 + `J Gen Physiol` + `Journal of General Physiology`, two alias
spellings), a different journal. Normalisation leaves 57 canonical names.

MIMIC tier conjunctions (docs/mimic/mimic-v0.1.md §4/§10), same artifact:

    -- provenance 960; +recording_mode 921; L1 820; L2 680
    -- +n 338; +temperature_c 23; +ph/bath/pipette/holding 11 (L3 complete)
    -- L1 ∩ temperature_c 53; L1/L2 excluding stimulus_type='OTHER' 589/470
    -- evidence_location non-NULL 958; expression_system maxlen 296, >90 455
"""

import json
import os
import re
import sqlite3
import subprocess
import sys
from pathlib import Path

from tests.test_site_build import DB_PATH, REPO_ROOT, requires_db

SCRIPT = REPO_ROOT / "scripts" / "corpus-stats.py"
DOC = REPO_ROOT / "docs" / "research" / "2026-11-06-corpus-baseline.md"


def _run(
    json_out: Path | None = None, db: Path | None = DB_PATH
) -> tuple[dict | None, str]:
    """Run the stats script read-only; return (JSON payload or None, Markdown).

    ``db=None`` omits ``--db`` so the script uses its default relative path —
    the label the committed report embeds.
    """
    env = dict(os.environ, PYTHONPATH=str(REPO_ROOT / "src"))
    cmd = [sys.executable, str(SCRIPT)]
    if db is not None:
        cmd += ["--db", str(db)]
    if json_out is not None:
        cmd += ["--json", str(json_out)]
    proc = subprocess.run(
        cmd, capture_output=True, text=True, env=env, check=True, cwd=REPO_ROOT
    )
    payload = json.loads(json_out.read_text(encoding="utf-8")) if json_out else None
    return payload, proc.stdout


def run_stats(out_path: Path) -> dict:
    """Run the stats script read-only; return its JSON payload."""
    return _run(out_path)[0]


def run_markdown() -> str:
    """Run the stats script read-only; return the Markdown it prints."""
    return _run(db=None)[1]


def _report_body(generated: str) -> str:
    """The script's output minus its H1, headings demoted one level.

    The script's H1 is the document's own title, so §4 embeds the body only.
    """
    body = generated.split("\n", 1)[1].lstrip("\n")
    return re.sub(r"^(#+) ", r"#\1 ", body, flags=re.M).rstrip("\n")


def _section4(doc: str) -> str:
    """The §4 body: everything between its heading and §5's heading."""
    after = doc.split("## 4. Generated report\n\n", 1)[1]
    return after.split("\n## 5. ", 1)[0].rstrip("\n")


def _scalar(sql: str) -> int:
    con = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    try:
        return con.execute(sql).fetchone()[0]
    finally:
        con.close()


def _pairs(sql: str) -> dict:
    con = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    try:
        return dict(con.execute(sql).fetchall())
    finally:
        con.close()


