@requires_db
def test_stats_are_deterministic(tmp_path):
    """Same artifact + same code → byte-identical JSON *and* Markdown.

    The script's docstring claims two runs are byte-identical; the report is
    the Markdown, so the comparison has to cover stdout, not only the
    ``sort_keys=True`` JSON (which would hide dict-ordering drift).
    """
    _run(tmp_path / "a.json")
    _run(tmp_path / "b.json")
    assert (tmp_path / "a.json").read_bytes() == (tmp_path / "b.json").read_bytes()
    assert run_markdown() == run_markdown()


@requires_db
def test_embedded_report_matches_generated_output():
    """The document's generated section is byte-identical to a fresh run.

    This is the mechanism behind "the report cannot go stale silently": the
    §4 body in docs/research/2026-11-06-corpus-baseline.md is exactly the
    script's output minus its H1, headings demoted one level. The comparison
    is whole-section equality, not substring containment, so a hand-written
    sentence can be added neither before nor after the block.
    """
    generated = run_markdown()
    embedded = _report_body(generated)
    doc = DOC.read_text(encoding="utf-8")
    section = _section4(doc)
    assert section == embedded
    # self-vectors (CODING_STANDARDS rule 4): feed known-escape documents to
    # the collector itself, not to a string comparison beside it.
    # 1. a prose line appended after the block — the escape form the old
    #    substring check (`embedded in doc`) accepted;
    appended = doc.replace(
        section + "\n", section + "\nA hand-written note appended.\n", 1
    )
    assert appended != doc
    assert embedded in appended  # the old check would still pass
    assert _section4(appended) != embedded
    # 2. a prose line inserted before the block;
    prepended = doc.replace(
        "## 4. Generated report\n\n",
        "## 4. Generated report\n\nA hand-written preface.\n\n",
        1,
    )
    assert prepended != doc
    assert embedded in prepended
    assert _section4(prepended) != embedded
    # 3. a one-number drift inside the block.
    drift = doc.replace("| 960 |", "| 961 |", 1)
    assert drift != doc
    assert _section4(drift) != embedded


@requires_db
def test_mimic_tier_and_vocabulary_census():
    """The MIMIC draft's §4/§10 tier conjunctions and §6.1 stimulus counts.

    These numbers are census SQL, not script output; pinning them here keeps
    the draft honest (the coverage snapshot in the script only counts single
    columns, never a conjunction).
    """
    prov = (
        "evidence_quote is not null and confidence is not null "
        "and condition_key is not null and measurement_id is not null"
    )
    l1 = f"{prov} and recording_mode is not null and stimulus_type is not null"
    l2 = f"{l1} and cell_type is not null and expression_system is not null"
    base = "select count(*) from biophysics_experiment where "
    assert _scalar(base + prov) == 960
    assert _scalar(base + prov + " and recording_mode is not null") == 921
    assert _scalar(base + l1) == 820
    assert _scalar(base + l2) == 680
    assert _scalar(base + l2 + " and n is not null") == 338
    assert _scalar(base + l2 + " and n is not null and temperature_c is not null") == 23
    l3 = (
        l2
        + " and n is not null and temperature_c is not null and ph is not null"
        " and bath_solution is not null and pipette_solution is not null"
        " and holding_potential_mv is not null"
    )
    assert _scalar(base + l3) == 11
    # temperature as an L1 counterfactual (draft §4), and the OTHER-free view
    assert _scalar(base + l1 + " and temperature_c is not null") == 53
    assert _scalar(base + l1 + " and stimulus_type != 'OTHER'") == 589
    assert _scalar(base + l2 + " and stimulus_type != 'OTHER'") == 470
    # §6.1 counts (OSMOTIC has zero rows and so is absent here)
    assert _pairs(
        "select coalesce(stimulus_type, '(null)'), count(*) "
        "from biophysics_experiment group by 1"
    ) == {
        "PRESSURE_CLAMP": 317,
        "SUCTION": 118,
        "OTHER": 239,
        "(null)": 124,
        "INDENTATION": 95,
        "TOUCH": 22,
        "HYPOTONIC": 15,
        "SHEAR_STRESS": 12,
        "POSITIVE_PRESSURE": 11,
        "MEMBRANE_STRETCH": 7,
    }
    # §5.3/§6.4 measured facts and §3's 99.8% evidence-location coverage
    assert _scalar(
        "select max(length(expression_system)) from biophysics_experiment"
    ) == 296
    assert _scalar(
        "select count(*) from biophysics_experiment "
        "where length(expression_system) > 90"
    ) == 455
    assert _scalar(
        "select count(evidence_location) from biophysics_experiment"
    ) == 958
