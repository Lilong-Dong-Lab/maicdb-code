class TestInputCensuses:
    def test_p50_corpus(self, records, census_snapshot):
        """Census: biophysics.p50_records / p50_unit_split /
        p50_sign_split (generated pins, snapshot keys — COUNT of
        p50_value rows, GROUP BY p50_unit, and the negative/positive/
        zero sign split over the mmHg domain)."""
        bp = census_snapshot["biophysics"]
        assert len(records) == bp["p50_records"]
        units = {r.p50_unit: sum(1 for x in records if x.p50_unit == r.p50_unit)
                 for r in records}
        assert units == bp["p50_unit_split"]
        neg = sum(1 for r in records if r.p50_mmhg < 0)
        pos = sum(1 for r in records if r.p50_mmhg > 0)
        zero = sum(1 for r in records if r.p50_mmhg == 0)
        assert [neg, pos, zero] == bp["p50_sign_split"]

    def test_condition_key_degeneration(self, engine, census_snapshot):
        """Census: biophysics.p50_condition_key_degeneracy (generated
        pin, snapshot key — the cluster-fallback justification: P50
        rows with a condition_key == DISTINCT condition_key, so the
        module clusters at publication level, see
        ``biophysics.cluster_key``)."""
        with engine.connect() as conn:
            n, k = conn.execute(
                text(
                    "SELECT COUNT(*), COUNT(DISTINCT condition_key) FROM "
                    "biophysics_experiment WHERE p50_value IS NOT NULL "
                    "AND condition_key IS NOT NULL"
                )
            ).one()
        assert [n, k] == census_snapshot["biophysics"][
            "p50_condition_key_degeneracy"
        ]

    def test_cell_structure(self, records, census_snapshot):
        """Census: biophysics.p50_cell_census (generated pin, snapshot
        key — n and distinct publications per (family, stimulus_type)
        cell over P50 rows; snapshot keys are ``FAMILY/STIMULUS``
        strings)."""
        cells: dict[tuple[str, str | None], tuple[int, int]] = {}
        for r in records:
            key = (r.family, r.stimulus_type)
            n, pubs = cells.get(key, (0, 0))
            cells[key] = (n + 1, pubs)  # pubs filled below
        pubs_map: dict[tuple[str, str | None], set[int]] = {}
        for r in records:
            pubs_map.setdefault((r.family, r.stimulus_type), set()).add(
                r.publication_id
            )
        for key, pubset in pubs_map.items():
            n, _ = cells[key]
            cells[key] = (n, len(pubset))
        assert {f"{k[0]}/{k[1]}": [v[0], v[1]] for k, v in cells.items()} == (
            census_snapshot["biophysics"]["p50_cell_census"]
        )




