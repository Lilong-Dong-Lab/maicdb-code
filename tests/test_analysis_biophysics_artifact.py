class TestThresholdMeta:
    def test_ten_cells_dual_report(self, cells, census_snapshot):
        """Census: biophysics.threshold_meta_cells / meta_piezo_pc
        (generated pins, snapshot keys). Pooled |P50| geometric means
        stay transcribed approx pins, dual-reported (kPa = mmHg ×
        0.133322387415 exactly — one identity pinned numerically)."""
        assert len(cells) == census_snapshot["biophysics"]["threshold_meta_cells"]
        pz = cells[("PIEZO", "PRESSURE_CLAMP")]
        assert [pz.k, pz.n] == [
            census_snapshot["biophysics"]["meta_piezo_pc"]["k"],
            census_snapshot["biophysics"]["meta_piezo_pc"]["n"],
        ]
        assert pz.pooled_mmhg == pytest.approx(35.1375, abs=1e-4)
        assert pz.pooled_kpa == pytest.approx(
            pz.pooled_mmhg * KPA_PER_MMHG, abs=1e-12
        )
        assert pz.pooled_kpa == pytest.approx(4.6846, abs=1e-4)

    def test_heterogeneity_is_real(self, cells):
        """Module-output determinism: I² spans 0.61–0.97 across the
        identifiable cells — high between-paper heterogeneity, the
        honest Track-B result. Anchors: PIEZO/PC 0.9419, OSCA/PC
        0.9686, K2P/SUCTION 0.6111."""
        assert cells[("PIEZO", "PRESSURE_CLAMP")].i2 == pytest.approx(
            0.9419, abs=1e-4
        )
        assert cells[("OSCA_TMEM63", "PRESSURE_CLAMP")].i2 == pytest.approx(
            0.9686, abs=1e-4
        )
        assert cells[("K2P", "SUCTION")].i2 == pytest.approx(0.6111, abs=1e-4)

    def test_identifiability_gate(self, cells, census_snapshot):
        """Census: biophysics.cell_identifiability (generated pin,
        snapshot key — the three k==1 cells' gate flags; identifiable
        iff max records-per-publication within the cell ≥ 2). TRP/PC
        (1 pub, 1 record) stays descriptive: CI/PI/τ²/Q/I² None, pooled
        still reported (transcribed approx). TMC/PC and K2P/PC have an
        identifiable s²_w but k=1 → inferential fields None."""
        gate = {
            f"{fam}/{stim}": cells[(fam, stim)].identifiable
            for fam, stim in (
                ("K2P", "PRESSURE_CLAMP"),
                ("TMC", "PRESSURE_CLAMP"),
                ("TRP", "PRESSURE_CLAMP"),
            )
        }
        assert gate == census_snapshot["biophysics"]["cell_identifiability"]
        trp = cells[("TRP", "PRESSURE_CLAMP")]
        assert trp.ci_mmhg is None and trp.pi_mmhg is None and trp.i2 is None
        assert trp.pooled_mmhg == pytest.approx(18.0, abs=1e-12)
        for key in (("TMC", "PRESSURE_CLAMP"), ("K2P", "PRESSURE_CLAMP")):
            c = cells[key]
            assert c.k == 1
            assert c.ci_mmhg is None and c.pi_mmhg is None

    def test_sign_split_disclosed(self, cells, census_snapshot):
        """Census: biophysics.cell_negative_n (generated pin, snapshot
        key — SUM(p50_value < 0) per cell, ALL 10 cells). Mixed signs
        INSIDE cells (e.g. PIEZO/PC) is the disclosed sign-convention
        finding."""
        assert {f"{c.family}/{c.stimulus_type}": c.negative_n
                for c in cells.values()} == census_snapshot["biophysics"][
            "cell_negative_n"
        ]

    def test_ci_pi_brackets(self, cells):
        """Structural check on the determinism outputs: every
        identifiable cell's CI brackets its pooled mean; the k=2
        PIEZO/PP cell's Higgins PI is (deliberately) enormous — tau²
        with 2 papers — disclosed here so the width never surprises."""
        for c in cells.values():
            if c.ci_mmhg is not None:
                lo, hi = c.ci_mmhg
                assert lo < c.pooled_mmhg < hi
        pp = cells[("PIEZO", "POSITIVE_PRESSURE")]
        assert pp.pi_mmhg is not None
        assert pp.pi_mmhg[0] < 1.0  # wider than the data range: k=2 tau²


class TestKineticsAtlas:
    def test_cells_and_totals(self, engine, census_snapshot):
        """Census: biophysics.kinetics_cells / kinetics_totals /
        kinetics_genes (generated pins, snapshot keys — COUNT per tau
        column, gene × kind cell count, the gene set with tau data)."""
        bk = census_snapshot["biophysics"]
        ka = kinetics_atlas(engine)
        assert len(ka) == bk["kinetics_cells"]
        totals = {"tau_act": 0, "tau_inact": 0, "tau_deact": 0}
        genes: set[str] = set()
        for c in ka:
            totals[c.kind] += c.k
            genes.add(c.gene_symbol)
        assert totals == bk["kinetics_totals"]
        assert sorted(genes) == bk["kinetics_genes"]

    def test_anchor(self, engine, census_snapshot):
        """Census: biophysics.kinetics_asic_tau_inact (generated pin,
        snapshot key — k and n_pubs for the ASIC tau_inact cell). The
        geo mean / median stay transcribed approx pins."""
        ka = kinetics_atlas(engine)
        anchor = next(c for c in ka if c.gene_symbol == "ASIC"
                      and c.kind == "tau_inact")
        kp = census_snapshot["biophysics"]["kinetics_asic_tau_inact"]
        assert [anchor.k, anchor.n_pubs] == [kp["k"], kp["n_pubs"]]
        assert anchor.geo_mean_ms == pytest.approx(437.692, abs=1e-3)
        assert anchor.median_ms == pytest.approx(513.809, abs=1e-3)
        assert anchor.min_ms > 0
        assert anchor.min_ms <= anchor.median_ms <= anchor.max_ms


class TestLabSpread:
    def test_nine_cells_with_anchors(self, records, census_snapshot):
        """Census: biophysics.lab_spread_cells / lab_spread_piezo1_pc /
        lab_spread_mscl_suction (generated pins, snapshot keys; gate =
        ≥2 distinct publications per (gene, stimulus)). The geo means
        and geo sds stay transcribed approx pins. Signed range kept
        as-reported: MscL/PC spans −163.0..255.0 — the sign-convention
        inconsistency made visible per gene."""
        bl = census_snapshot["biophysics"]
        ls = lab_spread(records)
        assert len(ls) == bl["lab_spread_cells"]
        by_key = {(c.gene_symbol, c.stimulus_type): c for c in ls}
        pz = by_key[("PIEZO1", "PRESSURE_CLAMP")]
        assert [pz.k, pz.n] == [
            bl["lab_spread_piezo1_pc"]["k"],
            bl["lab_spread_piezo1_pc"]["n"],
        ]
        assert pz.geo_mean_mmhg == pytest.approx(35.14, abs=1e-2)
        assert pz.geo_sd_log10 == pytest.approx(0.199, abs=1e-3)
        ms = by_key[("MscL", "SUCTION")]
        assert [ms.k, ms.n] == [
            bl["lab_spread_mscl_suction"]["k"],
            bl["lab_spread_mscl_suction"]["n"],
        ]
        assert ms.geo_mean_mmhg == pytest.approx(83.20, abs=1e-2)
        assert ms.geo_sd_log10 == pytest.approx(0.1243, abs=1e-3)
        mpc = by_key[("MscL", "PRESSURE_CLAMP")]
        assert (mpc.min_mmhg, mpc.max_mmhg) == (-163.0, 255.0)


class TestBoltzmannDemo:
    def test_four_p50_pairs_methods_demo(self, engine, census_snapshot):
        """Census: biophysics.boltzmann_pairs / boltzmann_top_token_overlap
        (generated pins, snapshot keys). The pair ids stay transcribed
        MAIC:BX accession pins (consumes P1's join: 6 narrowed pairs,
        p50-kind subset 4) and the demo floats stay transcribed approx
        pins (00197→00190: P50 76.3 mmHg, slope 5.0, ΔG 15.26 kBT —
        METHODS DEMO, n forbids claims; the negative-P50 pairs yield
        negative ΔG, the same sign-convention artifact disclosed
        module-wide)."""
        with engine.connect() as conn:
            ck = {
                str(r["maicdb_id"]): (r["condition_key"] or "")
                for r in conn.execute(
                    text("SELECT maicdb_id, condition_key FROM "
                         "biophysics_experiment")
                ).mappings()
            }
        demo = boltzmann_demo(engine, ck)
        assert len(demo) == census_snapshot["biophysics"]["boltzmann_pairs"]
        ids = [(d["slope_maicdb_id"], d["threshold_maicdb_id"]) for d in demo]
        # v1.1 renumbering: +1 below the Duru 2026 insertion block
        # (00199–00206), +12 above it — same rows, same condition_keys.
        assert ids == [
            ("MAIC:BX:00198", "MAIC:BX:00191"),
            ("MAIC:BX:00761", "MAIC:BX:00760"),
            ("MAIC:BX:00797", "MAIC:BX:00796"),
            ("MAIC:BX:00818", "MAIC:BX:00811"),
        ]
        top = demo[0]
        assert top["token_overlap"] == census_snapshot["biophysics"][
            "boltzmann_top_token_overlap"
        ]
        assert top["p50_mmhg"] == pytest.approx(76.3, abs=1e-9)
        assert top["slope"] == 5.0
        assert top["delta_g_kbt"] == pytest.approx(15.26, abs=1e-2)
        neg = demo[1]
        assert neg["delta_g_kbt"] == pytest.approx(-8.025, abs=1e-2)
