"""Shared pytest fixtures for MAIC-DB schema tests.

Each test gets a fresh in-memory SQLite database with the full schema applied.
``StaticPool`` pins a single connection so the in-memory database persists
across the session's connection checkouts.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from sqlalchemy import create_engine
from sqlalchemy.engine import Engine
from sqlalchemy.orm import Session
from sqlalchemy.pool import StaticPool

from maicdb.database import create_all

CENSUS_SNAPSHOT_PATH = Path(__file__).resolve().parent / "census_snapshot.json"


@pytest.fixture(scope="session")
def census_snapshot() -> dict[str, object]:
    """The frozen census record backing every generated pin.

    Regenerated by ``maicdb-census --write`` (or
    ``scripts/derive-census-clean.sh``) at each freeze retarget; the PR
    diff of this file is the human review of the drift.
    """
    return json.loads(CENSUS_SNAPSHOT_PATH.read_text(encoding="utf-8"))


@pytest.fixture()
def engine() -> Engine:
    eng = create_engine(
        "sqlite://",
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
        future=True,
    )
    from sqlalchemy import event

    @event.listens_for(eng, "connect")
    def _enable_foreign_keys(dbapi_connection, _record):
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA foreign_keys=ON")
        cursor.close()
    create_all(eng)
    yield eng
    eng.dispose()


@pytest.fixture()
def session(engine: Engine) -> Session:
    with Session(engine) as s:
        yield s
