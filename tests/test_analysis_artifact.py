"""Artifact-gated pins for the P1 harmonization layer.

Census-class pins compare a freshly derived value against a key of the
generated snapshot ``tests/census_snapshot.json`` (the key is cited in
each test docstring; the snapshot is regenerated by ``maicdb-census
--write`` — see CODING_STANDARDS.md §6). Float conversions, MAIC:BX
accessions, and structural assertions stay transcribed with their
re-derivation path. Freeze: ``data-v1.2``.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from sqlalchemy import text

from maicdb.analysis.activity import p_activity
from maicdb.analysis.joins import (
    narrow_by_condition_key,
    same_fit_candidates,
    same_fit_marker_hits,
)
from maicdb.analysis.replicates import coalesce_replicates
from maicdb.analysis.units import length_to_um, pressure_to_mmhg, tension_to_mnm
from maicdb.query import open_readonly

DB_PATH = Path(__file__).parents[1] / "db" / "maicdb.sqlite"

requires_db = pytest.mark.skipif(
    not DB_PATH.exists(), reason=f"published DB not found at {DB_PATH}"
)

pytestmark = requires_db


@pytest.fixture(scope="module")
def engine():
    eng = open_readonly(DB_PATH)
    yield eng
    eng.dispose()


class TestUnitConversionPins:
    def test_psi_rows_convert(self, engine, census_snapshot):
        """Census: corpus.p50_psi_rows (generated pin, snapshot key).
        Converted expectations follow from the exact psi→Pa→mmHg
        constants in units.py, rounded to 4 dp."""
        with engine.connect() as conn:
            rows = conn.execute(
                text("SELECT p50_value FROM biophysics_experiment WHERE p50_unit='psi'")
            ).scalars().all()
        assert len(rows) == census_snapshot["corpus"]["p50_psi_rows"]
        got = sorted(round(pressure_to_mmhg(v, "psi").value, 4) for v in rows)
        assert got == [51.7149, 67.2294, 82.7439, 186.1737]

    def test_dyn_cm_identity_holds_all_rows(self, engine, census_snapshot):
        """Census: corpus.t50_dyncm_rows (generated pin, snapshot key);
        the dyn/cm ≡ mN/m identity must leave every value numerically
        unchanged."""
        with engine.connect() as conn:
            rows = conn.execute(
                text("SELECT t50_value FROM biophysics_experiment WHERE t50_unit='dyn/cm'")
            ).scalars().all()
        assert len(rows) == census_snapshot["corpus"]["t50_dyncm_rows"]
        assert all(tension_to_mnm(v, "dyn/cm").value == v for v in rows)

    def test_nm_rows_convert(self, engine, census_snapshot):
        """Census: corpus.x50_nm_rows (generated pin, snapshot key);
        conversion is nm × 0.001 → µm."""
        with engine.connect() as conn:
            rows = conn.execute(
                text("SELECT x50_value FROM biophysics_experiment WHERE x50_unit='nm'")
            ).scalars().all()
        assert len(rows) == census_snapshot["corpus"]["x50_nm_rows"]
        assert all(length_to_um(v, "nm").value == pytest.approx(v * 0.001) for v in rows)


class TestReplicateCoalescePins:
    def test_coalesce_buckets(self, engine, census_snapshot):
        """Census: replicates.coalesce_buckets (generated pin, snapshot
        key — bucket = coalesce over every biophysics_experiment row;
        "n_cells" never occurs because the column is empty in the
        artifact)."""
        with engine.connect() as conn:
            rows = conn.execute(
                text("SELECT n_cells, n FROM biophysics_experiment")
            ).all()
        buckets: dict[str, int] = {}
        for n_cells, n_text in rows:
            rep = coalesce_replicates(n_cells, n_text)
            buckets[rep.source] = buckets.get(rep.source, 0) + 1
        assert buckets == census_snapshot["replicates"]["coalesce_buckets"]


class TestPActivityPins:
    def test_pactivity_buckets(self, engine, census_snapshot):
        """Census: activity.pactivity_bases (generated pin, snapshot key
        — bucket = p_activity over every bioactivity row joined to
        compound.molecular_weight)."""
        with engine.connect() as conn:
            rows = conn.execute(
                text(
                    "SELECT ba.activity_value, ba.activity_units, "
                    "c.molecular_weight FROM bioactivity ba "
                    "LEFT JOIN compound c ON c.id = ba.compound_id"
                )
            ).all()
        buckets: dict[str, int] = {}
        for value, unit, mw in rows:
            pa = p_activity(value, unit, mw)
            buckets[pa.basis] = buckets.get(pa.basis, 0) + 1
        assert buckets == census_snapshot["activity"]["pactivity_bases"]


class TestSameFitJoinPins:
    def test_marker_hits(self, engine, census_snapshot):
        """Census: joins.marker_hit_count (generated pin, snapshot key);
        the by-id map stays transcribed — the seven marker rows are
        MAIC:BX accession pins (v1.1 renumbering: +1 below the Duru 2026
        insertion block 00199–00206, +12 above it — same rows)."""
        hits = same_fit_marker_hits(engine)
        assert len(hits) == census_snapshot["joins"]["marker_hit_count"]
        by_id = {h.maicdb_id: h.kind for h in hits}
        assert by_id == {
            "MAIC:BX:00111": "t50",
            "MAIC:BX:00148": "ambiguous",
            "MAIC:BX:00198": "p50",
            "MAIC:BX:00761": "p50",
            "MAIC:BX:00797": "p50",
            "MAIC:BX:00805": "t50",
            "MAIC:BX:00818": "p50",
        }

    def test_candidates_and_narrowing(self, engine, census_snapshot):
        """Census: joins.candidate_count (generated pin, snapshot key);
        the narrowed pairs stay transcribed — MAIC:BX accession pins, the
        live result of the deterministic rule in joins.py
        (narrow_by_condition_key), pinned so any change in the rule shows
        up as a test delta."""
        candidates = same_fit_candidates(engine)
        assert len(candidates) == census_snapshot["joins"]["candidate_count"]
        with engine.connect() as conn:
            keys = {
                row[0]: (row[1] or "")
                for row in conn.execute(
                    text("SELECT maicdb_id, condition_key FROM biophysics_experiment")
                )
            }
        narrowed = narrow_by_condition_key(candidates, keys)
        pairs = sorted(
            (c.slope_maicdb_id, c.threshold_maicdb_id, c.kind) for c in narrowed
        )
        assert pairs == [
            ("MAIC:BX:00111", "MAIC:BX:00110", "t50"),
            ("MAIC:BX:00198", "MAIC:BX:00191", "p50"),
            ("MAIC:BX:00761", "MAIC:BX:00760", "p50"),
            ("MAIC:BX:00797", "MAIC:BX:00796", "p50"),
            ("MAIC:BX:00805", "MAIC:BX:00804", "t50"),
            ("MAIC:BX:00818", "MAIC:BX:00811", "p50"),
        ]
        assert all(c.token_overlap is not None and c.token_overlap > 0 for c in narrowed)
