"""Artifact-gated pins for the P5 atlas (Track C).

Census-class pins are generated: the test recomputes the value and
compares it against a key of ``tests/census_snapshot.json`` (snapshot
key cited per test; regenerated by ``maicdb-census --write`` — see
CODING_STANDARDS.md §6). ΔP50 min/max and the selectivity top row stay
transcribed approx/label pins.

The dominant disclosed fact: the spec's structural-domain mapping and
much of the variant chain are DATA-THIN at data-v1.2 — every such
vacuity is pinned as the honest descriptive result (they are curation
demands, not analysis defects).
"""

from __future__ import annotations

from pathlib import Path

import pytest
from sqlalchemy import text

from maicdb.analysis.atlas import (
    compound_channel_matrix,
    delta_p50_table,
    selectivity_index,
)
from maicdb.query import open_readonly

DB_PATH = Path(__file__).parents[1] / "db" / "maicdb.sqlite"

requires_db = pytest.mark.skipif(
    not DB_PATH.exists(), reason=f"published DB not found at {DB_PATH}"
)

pytestmark = requires_db


@pytest.fixture(scope="module")
def engine():
    eng = open_readonly(DB_PATH)
    yield eng
    eng.dispose()


@pytest.fixture(scope="module")
def effects(engine):
    return delta_p50_table(engine)


@pytest.fixture(scope="module")
def matrix(engine):
    return compound_channel_matrix(engine)


class TestDeltaP50:
    def test_sixteen_rows_all_mmhg(self, effects, census_snapshot):
        """Census: atlas.delta_p50_rows / atlas.delta_p50_units
        (generated pins, snapshot keys); ΔP50 value range stays a
        transcribed approx pin (5.0–61.7)."""
        assert len(effects) == census_snapshot["atlas"]["delta_p50_rows"]
        from collections import Counter

        assert Counter(r.unit for r in effects) == census_snapshot["atlas"][
            "delta_p50_units"
        ]
        assert min(r.delta_p50 for r in effects) == 5.0
        assert max(r.delta_p50 for r in effects) == pytest.approx(61.7, abs=1e-9)

    def test_variant_chain_is_data_thin(self, effects, census_snapshot):
        """Census pins for every link of the spec's variant chain
        (generated pins, snapshot keys): variant-linked rows, the linked
        variants' NULL hgvs_protein / NULL functional_effect (pinned as
        non-null counts), the positions list, and the vacuous
        structural-domain mapping. Each vacuity is a curation demand
        (spec §5.2's own pattern), pinned here so future curation that
        fills them turns this test green-on-new facts, not silently."""
        assert (
            sum(1 for r in effects if r.variant_linked)
            == census_snapshot["atlas"]["variant_linked_rows"]
        )
        assert (
            sum(1 for r in effects if r.variant is not None)
            == census_snapshot["atlas"]["variant_hgvs_nonnull"]
        )
        assert (
            sum(1 for r in effects if r.functional_effect is not None)
            == census_snapshot["atlas"]["variant_effect_nonnull"]
        )
        assert sorted(
            r.variant_position for r in effects if r.variant_position is not None
        ) == census_snapshot["atlas"]["variant_positions"]
        assert (
            sum(1 for r in effects if r.domains)
            == census_snapshot["atlas"]["domain_covered_total"]
        )

    def test_gene_split(self, effects, census_snapshot):
        """Census: atlas.delta_p50_gene_split (generated pin, snapshot
        key — JOIN channel GROUP BY gene over ΔP50 rows)."""
        from collections import Counter

        counts = Counter(r.gene_symbol for r in effects)
        assert counts == census_snapshot["atlas"]["delta_p50_gene_split"]


class TestMatrix:
    def test_sparse_shape(self, matrix, census_snapshot):
        """Census: atlas.matrix_cells / atlas.matrix_activity_rows /
        atlas.matrix_multi_channel_excess (generated pins, snapshot keys
        — 137 activity rows over 73 distinct compound × channel pairs,
        64 excess rows aggregated into cell means; possible cells
        69 × 9 = 621 → ~12% populated: sparse by construction)."""
        assert len(matrix) == census_snapshot["atlas"]["matrix_cells"]
        assert sum(c.k for c in matrix) == census_snapshot["atlas"][
            "matrix_activity_rows"
        ]
        assert sum(c.k - 1 for c in matrix) == census_snapshot["atlas"][
            "matrix_multi_channel_excess"
        ]

    def test_value_coverage_and_bases(self, engine, matrix, census_snapshot):
        """Census: atlas.cells_with_pactivity and
        atlas.matrix_basis_totals (generated pins, snapshot keys —
        basis totals over all 137 measurements equal P1's
        activity.pactivity_bases); corpus.bioactivity_pchembl_null
        (generated pin — pchembl NULL on ALL rows; the value-axis
        choice rests on it; a future release that fills pchembl must
        revisit this module)."""
        with engine.connect() as conn:
            pchembl_null = conn.execute(
                text("SELECT COUNT(*) FROM bioactivity WHERE pchembl IS NULL")
            ).one()[0]
        assert pchembl_null == census_snapshot["corpus"]["bioactivity_pchembl_null"]
        with_value = [c for c in matrix if c.pactivity is not None]
        assert len(with_value) == census_snapshot["atlas"]["cells_with_pactivity"]
        bases: dict[str, int] = {}
        for c in matrix:
            for basis, n in c.basis_counts:
                bases[basis] = bases.get(basis, 0) + n
        assert bases == census_snapshot["atlas"]["matrix_basis_totals"]

    def test_family_distribution(self, matrix, census_snapshot):
        """Census: atlas.matrix_family_split (generated pin, snapshot
        key — JOIN channel GROUP BY family over the 73 pairs)."""
        from collections import Counter

        counts = Counter(c.family for c in matrix)
        assert counts == census_snapshot["atlas"]["matrix_family_split"]


class TestSelectivity:
    def test_rows_and_the_single_gapped_compound(self, matrix, census_snapshot):
        """Census: atlas.selectivity_rows / atlas.selectivity_gapped_rows
        (generated pins, snapshot keys). The top-gap row itself stays a
        transcribed determinism pin: gadolinium (Gd3+) — best TRAAK
        5.301, off-target TMC, gap 1.121 (inputs census-derivable from
        its bioactivity rows; determinism pin on the aggregation)."""
        si = selectivity_index(matrix)
        assert len(si) == census_snapshot["atlas"]["selectivity_rows"]
        gapped = [r for r in si if r.selectivity_gap is not None]
        assert len(gapped) == census_snapshot["atlas"]["selectivity_gapped_rows"]
        top = max(gapped, key=lambda r: r.selectivity_gap)
        assert top.compound_name == "gadolinium (Gd3+)"
        assert top.best_channel == "TRAAK"
        assert top.best_pactivity == pytest.approx(5.301, abs=1e-3)
        assert top.best_off_target_channel == "TMC"
        assert top.selectivity_gap == pytest.approx(1.121, abs=1e-3)
