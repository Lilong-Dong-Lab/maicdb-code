"""Vault seam — the single place maicdb-code knows the vault's location,
layout, and freeze contract.

Every vault reference outside this module goes through it:

* :func:`resolve_vault` — location discovery: an explicit argument wins,
  then the ``MAICDB_VAULT`` env var, then the sibling checkout
  ``../Project_DataBase_MAICDB`` next to this repo. The sibling form is
  a property of a source checkout (editable install / ``PYTHONPATH=src``);
  a wheel install must pass an explicit path or the env var.
* :class:`FrozenVault` — one vault checkout opened for reading under the
  freeze contract: ``verify()`` (clean tracked tree; with a tag required:
  tag resolves, HEAD descends from the tag, and the frozen surface
  byte-matches the code-side freeze manifest) plus typed accessors for
  everything the loader reads. The loader keeps the transforms; this
  module owns the paths.
* :func:`build_freeze_manifest` / :func:`load_freeze_manifest` — the
  freeze manifest (``db/freeze-manifest.json``, ADR-0007): the code-side
  pinned input contract. It names the freeze tag and the exact commit it
  tags, and closes the frozen surface (every tracked file under ``data/``
  and ``tools/literature-mining/configs/`` minus the two legal-churn
  exclude globs) with a sha256 per file. The loader's freeze constants
  (freeze date, schema version, conservation counts) live in it too —
  ``maicdb.loader`` reads them from here instead of carrying literals.

Resolution does no I/O and never *finds* a vault implicitly for library
callers: ``load_vault`` still takes an explicit path — only the CLI
entry point (``maicdb loader.main``) applies :func:`resolve_vault` to
its optional ``--vault`` argument.

Born 2026-11-15 (architecture-review candidate 3): discovery previously
lived in ``tests/test_loader.py`` and the layout constants in
``maicdb.loader``; both moved here unchanged. The freeze contract was
reworked from a git pathspec diff into the hash-pinned freeze manifest
in the follow-up PR (candidate 3 PR B, ADR-0007, 2026-11-16).
"""

from __future__ import annotations

import csv
import hashlib
import json
import os
import re
import subprocess
from datetime import date
from pathlib import Path

__all__ = ["CHANNEL_DIRS", "COUNT_KEYS", "DEFAULT_TAG", "FACT_TABLES",
           "FREEZE_MANIFEST_PATH", "FrozenVault", "LAYERS", "LAYER_TO_CONFIG",
           "SIBLING_NAME", "build_freeze_manifest", "load_freeze_manifest",
           "resolve_vault"]

#: Sentinel for "require the tag the freeze manifest pins" — the loader
#: resolves it to ``freeze_manifest["freeze_tag"]``; ``None`` keeps
#: meaning "skip freeze enforcement".
DEFAULT_TAG = object()

#: Default home of the freeze manifest (repo-relative; generated by
#: ``scripts/write-freeze-manifest.py``).
FREEZE_MANIFEST_PATH = Path(__file__).resolve().parents[2] / "db" / "freeze-manifest.json"

#: Sibling checkout name used by :func:`resolve_vault`'s last resort.
SIBLING_NAME = "Project_DataBase_MAICDB"

#: The 12 corpus layers in canonical sequence. Load-bearing beyond layout:
#: first-seen publication insertion (title dedup) follows this order at
#: load time.
LAYERS = ["piezo1", "piezo2", "trpv4", "asic", "mscs", "mscl", "osca",
          "tmc", "tresk", "traak", "trek-1", "trek-2"]

#: The same layers sorted — the frozen corpus's ``data/`` directory set
#: (presence/intactness checks; census: spec §4 — ``SELECT gene_symbol
#: FROM channel`` lowercased).
CHANNEL_DIRS = sorted(LAYERS)

#: Config file stem per layer (``tools/literature-mining/configs/<stem>.yaml``
#: — channel dashes stripped).
LAYER_TO_CONFIG = {layer: layer.replace("-", "") for layer in LAYERS}


def resolve_vault(explicit: str | Path | None = None) -> Path:
    """Vault discovery: an explicit argument wins, then ``$MAICDB_VAULT``,
    then the sibling checkout next to this repo. Returns the path
    UNVERIFIED — presence and freeze state are :meth:`FrozenVault.verify`
    (and the READ-based :meth:`FrozenVault.readable` probe) business."""
    if explicit:
        return Path(explicit)
    env = os.environ.get("MAICDB_VAULT")
    if env:
        return Path(env)
    # src/maicdb/vault.py → parents: [src/maicdb, src, repo root]
    return Path(__file__).resolve().parents[2].parent / SIBLING_NAME


def _git(vault: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(vault), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


# --------------------------------------------------------------------------- #
# Freeze manifest (ADR-0007) — the code-side pinned input contract
# --------------------------------------------------------------------------- #
#: The frozen surface: 12 layer datasets (``data/<ch>/**`` incl. per-layer
#: READMEs and ``data/db/``) + identity configs (``configs/*.yaml``).
FROZEN_SURFACE_PATHS = ("data", "tools/literature-mining/configs")

#: Manifest ``counts`` schema (ADR-0007): the identity tables pinned next to
#: the conservation facts. The FACT_TABLES sum must equal ``rows_total``.
COUNT_KEYS = ("publication", "channel", "structure",
              "biophysics", "bioactivity", "unmapped")
FACT_TABLES = ("biophysics", "bioactivity", "unmapped")


def _frozen_surface_files(vault: Path) -> list[str]:
    """Every TRACKED frozen-surface file, minus the two legal-churn exclude
    globs, sorted. Tracked-only (``git ls-files``) matters: the old pathspec
    diff compared commits, so untracked local scratch never failed it — the
    closed-set check keeps that semantics.

    Root-level schema docs (``data/*.md`` — extraction_schema.md's
    Rules/enum sections evolve with the validator; CLAUDE.md: "doc side
    lives in the vault's data/extraction_schema.md — change both together")
    and validator-state registries (``configs/*.json`` —
    composite_quote_registry, quote_landing_allowlist) are legal post-freeze
    churn. (2026-09-03 narrowing: the previous blanket ``data/ + configs/``
    pathspec over-captured docs, blocking vault skill-patch PR #66
    cross-repo — user decision, Option A.)
    The exclude semantics mirror git's ANCHORED ``(glob)`` pathspec exactly:
    in glob magic ``*`` does NOT cross ``/``, so ``:(glob)data/*.md`` matches
    only the 2 root docs — 45 further ``.md`` files under ``data/`` stay
    frozen. The un-anchored pathspec form once silently un-froze all 47
    ``data/**.md`` files instead of the 2 root docs (gate r1 MINOR,
    2026-09-03; anchored form re-verified against README-changing commit
    8cdb764; count erratum 48→47 per vault PR-#67-gate recount, same day).
    fnmatch's ``*`` crosses ``/``, so these are slash-count rules, not
    single-``*`` fnmatch — they re-derive the anchored set (747 files at
    data-v1.2).
    """
    out = _git(vault, "ls-files", "-z", "--", *FROZEN_SURFACE_PATHS)
    files = []
    for f in out.split("\0"):
        if not f:
            continue
        if (
            f.startswith("data/")
            and f.endswith(".md")
            and f.count("/") == 1  # root-only: the anchored (glob) semantics
        ):
            continue
        if (
            f.startswith("tools/literature-mining/configs/")
            and f.endswith(".json")
            and f.count("/") == 3  # configs/-root-only, same anchored rule
        ):
            continue
        files.append(f)
    return sorted(files)


def _blob_sha256(vault: Path, rev: str, f: str) -> str:
    """sha256 of the git BLOB bytes at ``rev`` — not working-tree bytes.

    LFS matters: an LFS-tracked path holds a pointer file in some checkouts
    and the smudged payload in others (observed 2026-11-16 — the same tag,
    132-byte pointer vs 2.97 MB 8YEZ.pdb), so the working tree is not a
    stable byte source. Blob bytes are per-commit stable; for LFS paths
    that pins the pointer, whose embedded sha256 oid pins the payload.
    """
    r = subprocess.run(["git", "-C", str(vault), "cat-file", "blob",
                        f"{rev}:{f}"], capture_output=True)
    if r.returncode != 0:
        raise RuntimeError(
            f"frozen surface: {f} is in the freeze manifest but not in "
            "the vault's frozen surface (deleted since the freeze?)")
    return hashlib.sha256(r.stdout).hexdigest()


def build_freeze_manifest(vault: Path, tag: str, *, freeze_date: str,
                          schema_version: str) -> dict:
    """Pin a vault freeze: identity + closed-set file inventory + row counts.

    Runs the freeze checks first (clean tree, tag resolves, HEAD descends
    from the tag), then hashes the git BLOB bytes of every frozen-surface
    file at the tagged commit (stable across checkouts — see
    :func:`_blob_sha256` for the LFS rationale). ``freeze_date`` (the
    declared freeze epoch, NOT a git fact — data-v1.1 and data-v1.2 share
    2026-11-08) and ``schema_version`` (the formal-schema version the code
    implements) are declarations the vault cannot derive, so they are
    required arguments. The conservation ``counts`` block is filled in by
    ``scripts/write-freeze-manifest.py`` from a dry load — routing counts
    are loader facts, not vault facts.
    """
    FrozenVault(vault, tag).verify()  # gate: clean tree, tag, ancestry
    tagged = _git(vault, "rev-list", "-n", "1", tag)
    files = {f: _blob_sha256(vault, tagged, f)
             for f in _frozen_surface_files(vault)}
    rows_per_layer = {}
    for layer in LAYERS:
        with (vault / "data" / layer / "extraction"
              / "extracted_measurements.csv").open(newline="", encoding="utf-8") as fh:
            rows_per_layer[layer] = sum(1 for _ in csv.DictReader(fh))
    return {
        "freeze_tag": tag,
        "vault_head": tagged,
        "freeze_date": freeze_date,
        "schema_version": schema_version,
        "rows_total": sum(rows_per_layer.values()),
        "rows_per_layer": rows_per_layer,
        "files": files,
    }


def load_freeze_manifest(path: Path | None = None) -> tuple[dict, str]:
    """Read + validate the freeze manifest. Returns (manifest, sha256-of-file).

    Fail-closed: missing file, missing keys, non-hex digests, or violated
    internal identities (rows_per_layer must sum to rows_total; the
    conservation counts, when present, must sum to rows_total) all raise.
    """
    p = Path(path) if path else FREEZE_MANIFEST_PATH
    if not p.exists():
        raise RuntimeError(
            f"freeze manifest not found: {p} — generate it with "
            "scripts/write-freeze-manifest.py (see ADR-0007)")
    raw = p.read_bytes()
    fm = json.loads(raw)
    for key in ("freeze_tag", "vault_head", "freeze_date", "schema_version",
                "rows_total", "rows_per_layer", "files"):
        if key not in fm:
            raise RuntimeError(f"freeze manifest {p}: missing key {key!r}")
    try:
        date.fromisoformat(fm["freeze_date"])  # raises on a malformed date
    except ValueError as e:
        raise RuntimeError(
            f"freeze manifest {p}: malformed freeze_date "
            f"{fm['freeze_date']!r} (must be an ISO date)") from e
    if sorted(fm["rows_per_layer"]) != sorted(LAYERS):
        raise RuntimeError(
            f"freeze manifest {p}: rows_per_layer keys != the 12 corpus layers")
    if fm["rows_total"] != sum(fm["rows_per_layer"].values()):
        raise RuntimeError(
            f"freeze manifest {p}: rows_total {fm['rows_total']} != "
            f"sum(rows_per_layer) {sum(fm['rows_per_layer'].values())}")
    for f, digest in fm["files"].items():
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise RuntimeError(
                f"freeze manifest {p}: {f}: digest is not a sha256 hex digest")
    counts = fm.get("counts")
    if counts is not None:
        missing = [t for t in FACT_TABLES if t not in counts]
        if missing:
            raise RuntimeError(
                f"freeze manifest {p}: counts missing fact tables {missing}")
        facts = sum(counts[t] for t in FACT_TABLES)
        if facts != fm["rows_total"]:
            raise RuntimeError(
                f"freeze manifest {p}: conservation counts sum {facts} != "
                f"rows_total {fm['rows_total']}")
    return fm, hashlib.sha256(raw).hexdigest()


class FrozenVault:
    """One vault checkout opened for reading under the freeze contract.

    Construction does no I/O; the accessors and :meth:`verify` do.
    """

    def __init__(self, vault: Path, require_tag: str | None = None,
                 freeze_manifest: dict | None = None) -> None:
        self.vault = Path(vault)
        self.require_tag = require_tag
        self.freeze_manifest = freeze_manifest

    # ------------------------------------------------------------------ #
    # Freeze contract
    # ------------------------------------------------------------------ #
    def verify(self) -> str:
        """The vault must be a clean git checkout; with a tag required the
        tag must point at HEAD's ancestry and — when a freeze manifest is
        given — the frozen surface must byte-match the manifest's pinned
        inventory (closed set: every file present, every hash matching, no
        extras). Returns the HEAD sha. Fully silent (quirk 11: every git
        probe captures its stdio)."""
        head = _git(self.vault, "rev-parse", "HEAD")
        # untracked files (local scratch) don't affect tracked freeze content
        status = _git(self.vault, "status", "--porcelain", "--untracked-files=no")
        if status:
            raise RuntimeError(f"vault tracked content modified:\n{status}")
        if self.require_tag:
            exists = subprocess.run(
                ["git", "-C", str(self.vault), "rev-parse", "--verify",
                 f"refs/tags/{self.require_tag}"],
                capture_output=True, text=True,
            ).returncode == 0
            if not exists:
                raise RuntimeError(f"tag {self.require_tag!r} not found in the vault")
            tagged = _git(self.vault, "rev-list", "-n", "1", self.require_tag)
            ancestor = subprocess.run(
                ["git", "-C", str(self.vault), "merge-base", "--is-ancestor",
                 tagged, head],
                capture_output=True, text=True,
            ).returncode == 0
            if not ancestor:
                raise RuntimeError(
                    f"tag {self.require_tag} ({tagged[:7]}) is not an ancestor of HEAD "
                    f"({head[:7]}) — history diverged from the freeze")
            if self.freeze_manifest is not None:
                self._check_freeze_manifest(tagged, head, self.freeze_manifest)
        return head

    def _check_freeze_manifest(self, tagged: str, head: str, fm: dict) -> None:
        """Closed-set comparison of the frozen surface against the manifest.

        Replaces the old ``git diff <tag>..<head> -- <pathspec>`` check
        (candidate 3 PR B / ADR-0007): the manifest pins the TAG's blob
        bytes, and hash-matching HEAD's blobs against it proves the frozen
        content unchanged since the tag — without tag→HEAD diff machinery,
        immune to LFS smudge state, and functional in shallow clones where
        deep history is absent.
        """
        if fm["freeze_tag"] != self.require_tag:
            raise RuntimeError(
                f"freeze manifest pins {fm['freeze_tag']!r} but {self.require_tag!r} "
                "was required — regenerate the freeze manifest (scripts/"
                "write-freeze-manifest.py, ADR-0007)")
        if fm["vault_head"] != tagged:
            raise RuntimeError(
                f"freeze manifest pins tag {self.require_tag} at {fm['vault_head'][:12]} "
                f"but the tag resolves to {tagged[:12]} — re-tagging a freeze "
                "tag with consumers is forbidden (vault progress record)")
        actual = _frozen_surface_files(self.vault)
        actual_set = set(actual)
        for f, want in fm["files"].items():
            got = _blob_sha256(self.vault, head, f)
            if got != want:
                raise RuntimeError(
                    f"frozen surface: {f} changed since {self.require_tag} "
                    f"(manifest sha256 {want[:12]}…, vault has {got[:12]}…) — "
                    "frozen content requires a new tagged release")
        extras = sorted(actual_set - set(fm["files"]))
        if extras:
            raise RuntimeError(
                "frozen surface: file(s) not in the freeze manifest: "
                f"{extras} — new frozen content requires a new tagged release "
                "and a regenerated manifest")

    def readable(self) -> bool:
        """Presence probe that READS (quirk 8): ``exists()`` and ``is_dir()``
        survive macOS TCC denial (stat succeeds, reads EPERM), so a stat-only
        probe reports a locked vault as present and the full-load tests fail
        red instead of skipping. One real open() of a tracked file settles it.
        """
        try:
            (self.vault / "README.md").open("rb").close()
            return True
        except OSError:
            return False

    def has_channel_dirs(self) -> bool:
        """All 12 frozen channel directories present under ``data/``."""
        return all((self.vault / "data" / ch).is_dir() for ch in CHANNEL_DIRS)

    # ------------------------------------------------------------------ #
    # Corpus reads
    # ------------------------------------------------------------------ #
    def measurements(self) -> list[dict]:
        rows = []
        for layer in LAYERS:
            path = (self.vault / "data" / layer / "extraction"
                    / "extracted_measurements.csv")
            with path.open(newline="", encoding="utf-8") as f:
                for r in csv.DictReader(f):
                    r["source_layer"] = layer
                    rows.append(r)
        return rows

    def configs(self) -> dict[str, dict]:
        import yaml  # justified dependency: vault configs are YAML
        cfgs = {}
        for layer in LAYERS:
            p = (self.vault / "tools/literature-mining/configs"
                 / f"{LAYER_TO_CONFIG[layer]}.yaml")
            cfgs[layer] = yaml.safe_load(p.read_text(encoding="utf-8"))
        return cfgs

    def zotero_authors(self) -> dict[str, list[str]]:
        """DOI → full author list from the vault's Zotero export (CSL-JSON).
        'author' entries: [{'family': 'Shan', 'given': 'Yu'}, …] → ["Shan Y", …]."""
        p = self.vault / ".pandoc/zotero-library-1.json"
        out: dict[str, list[str]] = {}
        for item in json.loads(p.read_text(encoding="utf-8")):
            doi = (item.get("DOI") or "").strip().lower()
            if not doi:
                continue
            authors = []
            for c in item.get("author") or []:
                fam, giv = c.get("family"), c.get("given")
                if fam:
                    authors.append(f"{fam} {giv[0]}".strip() if giv else fam)
            if authors:
                out.setdefault(doi, authors)
        return out

    # ------------------------------------------------------------------ #
    # piezo1 companion datasets (layout owned here; the loader transforms)
    # ------------------------------------------------------------------ #
    @property
    def piezo1_cross_references_json(self) -> Path:
        return self.vault / "data/piezo1/cross_references/piezo1_cross_references.json"

    @property
    def piezo1_structures_csv(self) -> Path:
        return self.vault / "data/piezo1/structures/piezo1_pdb_structures.csv"

    def piezo1_structure_detail(self, pdb_id: str) -> Path:
        return (self.vault / "data/piezo1/raw/piezo1_pdb_entries_detail"
                / f"{pdb_id}.json")

    @property
    def piezo1_compound_properties_csv(self) -> Path:
        return self.vault / "data/piezo1/compounds/piezo1_compounds_properties.csv"
